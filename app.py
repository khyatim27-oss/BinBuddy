import os
import sqlite3
import uuid
from datetime import datetime, timezone

import numpy as np
from PIL import Image, UnidentifiedImageError
from flask import Flask, jsonify, redirect, render_template, request, url_for
from werkzeug.utils import secure_filename

try:
    import tensorflow as tf
except ImportError:
    tf = None

ROOT = os.path.dirname(os.path.abspath(__file__))
UPLOAD_DIR = os.path.join(ROOT, "uploads")
MODEL_PATH = os.path.join(ROOT, "models", "waste_classifier.keras")
DB_PATH = os.path.join(ROOT, "binbuddy.db")
ALLOWED_EXTENSIONS = {"png", "jpg", "jpeg", "webp"}
CLASSES = ["dry_waste", "wet_waste"]
os.makedirs(UPLOAD_DIR, exist_ok=True)

app = Flask(__name__)
app.config["MAX_CONTENT_LENGTH"] = 8 * 1024 * 1024  # 8 MB upload limit
_model = None

def get_db():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn

def init_db():
    with get_db() as db:
        db.execute("""
            CREATE TABLE IF NOT EXISTS classifications (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                image_filename TEXT NOT NULL,
                predicted_category TEXT NOT NULL,
                verified_category TEXT NOT NULL,
                confidence REAL NOT NULL,
                created_at TEXT NOT NULL
            )
        """)

def load_model():
    global _model
    if _model is None and tf is not None and os.path.exists(MODEL_PATH):
        _model = tf.keras.models.load_model(MODEL_PATH)
    return _model

def prepare_image(path):
    image = Image.open(path).convert("RGB").resize((224, 224))
    arr = np.asarray(image, dtype=np.float32)
    return np.expand_dims(arr, axis=0)

def predict_image(path):
    model = load_model()
    if model is None:
        return None, 0.0, "Model not trained yet. Add dataset images and run train.py."
    probabilities = model.predict(prepare_image(path), verbose=0)[0]
    idx = int(np.argmax(probabilities))
    category = CLASSES[idx]
    confidence = float(probabilities[idx])
    # Treat low confidence as manual review, not a confident classification.
    if confidence < 0.60:
        return "unknown", confidence, "Low confidence: please choose the correct category manually."
    return category, confidence, "Prediction generated by the trained model."

@app.route("/")
def home():
    return render_template("index.html")

@app.route("/classify", methods=["GET", "POST"])
def classify():
    result = None
    error = None
    if request.method == "POST":
        upload = request.files.get("image")
        if not upload or not upload.filename:
            error = "Choose an image first."
        elif "." not in upload.filename or upload.filename.rsplit(".", 1)[1].lower() not in ALLOWED_EXTENSIONS:
            error = "Upload a JPG, JPEG, PNG, or WEBP image."
        else:
            safe_name = secure_filename(upload.filename)
            filename = f"{uuid.uuid4().hex}_{safe_name}"
            path = os.path.join(UPLOAD_DIR, filename)
            try:
                upload.save(path)
                # Verify the file is a readable image before prediction.
                with Image.open(path) as im:
                    im.verify()
                predicted, confidence, note = predict_image(path)
                result = {
                    "filename": filename,
                    "predicted": predicted or "not_available",
                    "confidence": round(confidence * 100, 1),
                    "note": note,
                    "can_confirm": predicted is not None
                }
            except (UnidentifiedImageError, OSError):
                if os.path.exists(path):
                    os.remove(path)
                error = "That file could not be read as an image. Try another photo."
    return render_template("classify.html", result=result, error=error)

@app.route("/confirm", methods=["POST"])
def confirm():
    filename = request.form.get("filename", "")
    predicted = request.form.get("predicted", "unknown")
    verified = request.form.get("verified", "")
    try:
        confidence = float(request.form.get("confidence", "0")) / 100.0
    except ValueError:
        confidence = 0.0
    if not filename or "/" in filename or "\\" in filename:
        return "Invalid image reference.", 400
    if verified not in CLASSES:
        return "Choose wet waste or dry waste.", 400
    if predicted not in CLASSES + ["unknown", "not_available"]:
        predicted = "unknown"
    with get_db() as db:
        db.execute(
            "INSERT INTO classifications (image_filename, predicted_category, verified_category, confidence, created_at) VALUES (?, ?, ?, ?, ?)",
            (filename, predicted, verified, max(0.0, min(confidence, 1.0)), datetime.now(timezone.utc).isoformat())
        )
    return redirect(url_for("dashboard", saved=1))

@app.route("/dashboard")
def dashboard():
    with get_db() as db:
        rows = db.execute("SELECT * FROM classifications ORDER BY id DESC LIMIT 100").fetchall()
        total = db.execute("SELECT COUNT(*) FROM classifications").fetchone()[0]
        wet = db.execute("SELECT COUNT(*) FROM classifications WHERE verified_category='wet_waste'").fetchone()[0]
        dry = db.execute("SELECT COUNT(*) FROM classifications WHERE verified_category='dry_waste'").fetchone()[0]
    return render_template("dashboard.html", rows=rows, total=total, wet=wet, dry=dry,
                           saved=request.args.get("saved") == "1")

@app.route("/health")
def health():
    model_ready = os.path.exists(MODEL_PATH)
    return jsonify({"app": "BinBuddy", "model_file_present": model_ready,
                    "tensorflow_available": tf is not None, "database": DB_PATH})

@app.errorhandler(413)
def too_large(_):
    return "Image too large. Maximum size is 8 MB.", 413

init_db()

if __name__ == "__main__":
    app.run(debug=True)
